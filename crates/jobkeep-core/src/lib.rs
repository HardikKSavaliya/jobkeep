//! Core types and traits for JobKeep.
//!
//! This crate holds the vocabulary shared by every other JobKeep crate:
//! identity ([`JobId`], [`WorkerId`], [`Queue`], [`Priority`]), the job lifecycle
//! ([`State`]), the user-facing [`Job`] trait with its [`JobContext`] and
//! [`JobError`], the [`Registry`] that runs stored jobs by name, and the storage side: the [`NewJob`] record and the
//! [`Storage`] trait that backends implement.

mod error;
mod job;
mod registry;
mod state;
mod storage;
mod types;

#[cfg(feature = "testing")]
pub mod testing;

pub use error::JobError;
pub use job::{Extensions, Job, JobContext, NewJob, Recurring};
pub use registry::{BoxFuture, Registry, RegistryError};
pub use state::{ParseStateError, State};
pub use storage::{
    FetchedJob, JobFilter, JobRecord, Outcome, Stats, Storage, StorageError, ensure_transition,
    parent_failed_error,
};
pub use types::{JobId, Priority, Queue, WorkerId};

#[cfg(feature = "macros")]
pub use jobkeep_macros::{job, recurring};

#[doc(hidden)]
pub mod __private {
    //! Used by code generated by `#[job]` and `#[recurring]`.
    pub use serde;
}

/// Re-exported so users of [`JobContext`] don't need a direct `tokio-util` dependency.
pub use tokio_util::sync::CancellationToken;
